export function getAllStates(): { id: string; name: string }[] {
  return INDIA_LOCATIONS.map(s => ({ id: s.id, name: s.name }));
}

export function getCitiesByState(
  stateIdOrName: string,
): { id: string; name: string; state_id: string }[] {
  if (!stateIdOrName) return [];
  const normalized = stateIdOrName.trim().toLowerCase();
  const matched = INDIA_LOCATIONS.find(
    s => s.id === normalized || s.name.toLowerCase() === normalized,
  );
  if (!matched) return [];
  return matched.cities.map(c => ({
    id: c.id,
    name: c.name,
    state_id: matched.id,
  }));
}

export function findCity(
  cityIdOrName: string,
): { city: CityData; state: StateData } | undefined {
  if (!cityIdOrName) return undefined;
  const normalized = cityIdOrName.trim().toLowerCase();
  for (const state of INDIA_LOCATIONS) {
    const city = state.cities.find(
      c => c.id === normalized || c.name.toLowerCase() === normalized,
    );
    if (city) {
      return { city, state };
    }
  }
  return undefined;
}
